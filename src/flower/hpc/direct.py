"""``scheduler: none`` — run a node's payload directly on the cluster host, as a detached process.

For a workstation or a server you can SSH into that has no batch system. Same interface as
:mod:`flower.hpc.slurm`, so the job executor keeps all its guarantees (write-ahead intent, idempotent
launch, batched polls, typed verdicts):

* **launch**: ``nohup setsid bash job.sh &`` inside the attempt directory, from the login shell of the
  host (``bash -lc``), so the payload sees that machine's own environment (PATH, conda, modules).
  ``setsid`` gives the payload its own process group: cancel signals the whole tree (mpirun, …).
* **job id**: the payload's PID, written by ``job.sh`` itself to ``.flower/owner/id`` (also the
  duplicate guard: a second copy of the same attempt exits with 97 at once).
* **idempotency**: ``mkdir .flower/launched`` is the launch lock. A retried launch after a dropped
  connection re-attaches to the recorded PID instead of starting a second copy.
* **liveness**: ``kill -0 PID`` plus, on Linux, ``/proc/PID/cwd`` == attempt dir (guards PID reuse).
  Dead without ``.flower/ec`` means the process was killed hard or the machine rebooted -> ``lost``.
* **several login nodes behind one address** (SCNet: each ssh connection may land on another node; their home
  filesystem is shared, their processes are not): the payload records its node in ``.flower/host``. A poll from
  another node reads the files (the exit code) but cannot see the process: that is no evidence of its death, so
  it is no miss, and nothing is killed from there. Cancel leaves ``.flower/cancelled``, which a watcher beside
  the payload, on its node, acts on.
* **time limit**: ``resources.time`` (or the node's ``timeout.total``) is enforced with coreutils
  ``timeout``; hitting it leaves ``.flower/timed_out`` and fails with class ``timeout``.

Pattern from Eleforge's ``runners/ssh_machine/runner.py`` (detached PID + exit-code file + LOST
watchdog), aiida ``core.direct``, dpdispatcher ``Shell`` and jobflow-remote's ``shell`` scheduler.
"""
from __future__ import annotations

import re
